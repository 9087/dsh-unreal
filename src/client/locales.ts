/** A translator the slot framework may inject for this plugin's namespace. */
export type Translator = (key: string) => string

/**
 * Narrow a built message key to one the English table actually defines.
 *
 * @param key - candidate key.
 * @returns the key, or `undefined` when no dictionary defines it.
 */
function messageKey(key: string): MsgKey | undefined {
  return Object.prototype.hasOwnProperty.call(en, key) ? (key as MsgKey) : undefined
}

/**
 * Message key naming one recorded tool.
 *
 * Derived from the wire name: the tools are `unreal_<verb>`, so
 * `unreal_set_property_value` is `tool.set_property_value`.
 *
 * @param tool - wire tool name.
 * @returns the key, or `undefined` for a tool this build has no copy for.
 */
export function toolKey(tool: string): MsgKey | undefined {
  return messageKey(`tool.${tool.replace(/^unreal_/, '')}`)
}

/**
 * Message key naming one classified failure code.
 *
 * @param code - e.g. `rc/unreachable` or `editorautomation/invalid-type`.
 * @returns the key, or `undefined` for a code this build has no copy for.
 */
export function errorKey(code: string): MsgKey | undefined {
  return messageKey(`error.${code}`)
}

/**
 * Resolve one message.
 *
 * @param t - the framework's translator, when the locale service provided one.
 * @param key - message key.
 * @returns the translated string, the English string, or the key itself.
 */
export function localize(_t: Translator | undefined, key: MsgKey): string {
  // Localization is disabled for now: the plugin is English-only.
  return en[key]
}
